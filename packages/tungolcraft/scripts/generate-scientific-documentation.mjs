import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
	listModelReferences,
	runBenchmarkFixtures,
} from '../dist/index.js'

const packageDirectory = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const fixtures = JSON.parse(readFileSync(
	path.join(packageDirectory, 'benchmarks', 'fixtures.json'),
	'utf8',
))
const report = runBenchmarkFixtures(fixtures, 'generated-document')
const references = listModelReferences()

function formatNumber(value) {
	const text = Number(value).toPrecision(12)
	return text.includes('e')
		? text.replace(/\.?0+e/, 'e')
		: text.replace(/(\.\d*?[1-9])0+$/, '$1').replace(/\.0+$/, '')
}

function formatTolerance(tolerance) {
	const parts = []
	if (tolerance.absolute != null) parts.push(`abs ${formatNumber(tolerance.absolute)}`)
	if (tolerance.relative != null) parts.push(`rel ${formatNumber(tolerance.relative)}`)
	return parts.join(' + ')
}

function escapeTable(value) {
	return String(value).replaceAll('|', String.raw`\|`).replaceAll('\n', ' ')
}

function renderValidation() {
	const lines = [
		'# Tungolcraft scientific validation',
		'',
		'<!-- Generated by scripts/generate-scientific-documentation.mjs. Do not edit by hand. -->',
		'',
		`Status: **${report.passed}/${report.total} benchmarks passing**.`,
		'',
		'## Tolerance policy',
		'',
		'Each fixture declares an absolute tolerance, a relative tolerance, or both.',
		'Tungolcraft accepts a result when:',
		'',
		'```text',
		'absoluteError <= absoluteTolerance + relativeTolerance * abs(expected)',
		'```',
		'',
		'Tolerances cover only stated numerical rounding and source precision. They',
		'are not observational uncertainty and are not silently widened when a test',
		'fails. A fixture model-version mismatch fails before numeric comparison.',
		'',
		'## Benchmark results',
		'',
		'| Fixture | Model | Expected | Actual | Tolerance | Source |',
		'| --- | --- | ---: | ---: | --- | --- |',
	]
	for (const result of report.results) {
		const fixture = fixtures.find(item => item.id === result.id)
		const source = fixture?.source
		const sourceTarget = source?.doi == null ? source?.url : `https://doi.org/${source.doi}`
		const sourceText = sourceTarget == null
			? source?.citation
			: `[${source.citation}](${sourceTarget})`
		lines.push(
			`| ${result.id} | \`${result.modelId}@${result.modelVersion}\` | `
			+ `${formatNumber(result.expected.value)} ${result.expected.unit} | `
			+ `${formatNumber(result.actual?.value)} ${result.actual?.unit} | `
			+ `${formatTolerance(result.tolerance)} | `
			+ `${escapeTable(sourceText ?? '—')} |`,
		)
	}
	lines.push(
		'',
		'## Evidence scope',
		'',
		'The corpus combines primary-source rounded reference values with analytic',
		'identities and limiting cases. NASA Earth fixtures test spherical bulk',
		'relations; IAU nominal constants test two-body and stellar relations; the',
		'Domingos et al. fixture checks the published empirical coefficient.',
		'Constructed identities isolate geometry and approximation implementation.',
		'',
		'Passing these fixtures demonstrates reproducibility within the declared',
		'models. It does not make Tungolcraft an ephemeris, climate simulator or',
		'long-term N-body stability proof.',
		'',
		'Run `npm run benchmarks --workspace=tungolcraft` for human-readable output.',
		'After building, `npm run benchmarks:json --workspace=tungolcraft` emits the',
		'machine-readable report.',
		'',
	)
	return lines.join('\n')
}

function renderModelReference() {
	const lines = [
		'# Tungolcraft model reference',
		'',
		'<!-- Generated by scripts/generate-scientific-documentation.mjs. Do not edit by hand. -->',
		'',
		'Every scientific model has an independent semantic version. Equations,',
		'coefficients, defaults, validity or interpretation changes require a model',
		'version increment even when the npm API shape does not change.',
		'',
		'| Model | Version | Kind | Benchmark | Primary source or derivation |',
		'| --- | --- | --- | --- | --- |',
	]
	for (const model of references) {
		const modelFixtures = fixtures.filter(fixture => fixture.modelId === model.id)
		const source = model.sources[0]
		const target = source?.doi == null ? source?.url : `https://doi.org/${source.doi}`
		const sourceText = target == null
			? source?.citation
			: `[${source.citation}](${target})`
		lines.push(
			`| \`${model.id}\` | \`${model.version}\` | \`${model.kind}\` | `
			+ `${modelFixtures.map(fixture => `\`${fixture.id}\``).join(', ')} | `
			+ `${escapeTable(sourceText ?? '—')} |`,
		)
	}
	lines.push(
		'',
		'The public `listModelReferences()` registry is the normative machine-readable',
		'source for complete summaries, assumptions and validity rules. This page is',
		'a release-readable index generated from that registry and the benchmark',
		'corpus.',
		'',
	)
	return lines.join('\n')
}

const documents = {
	'docs/VALIDATION.md': renderValidation(),
	'docs/MODEL-REFERENCE.md': renderModelReference(),
}

if (process.argv.includes('--stdout')) {
	process.stdout.write(`${JSON.stringify(documents)}\n`)
} else if (process.argv.includes('--check')) {
	const stale = Object.entries(documents)
		.filter(([relativePath, expected]) => {
			try {
				return readFileSync(path.join(packageDirectory, relativePath), 'utf8') !== expected
			} catch {
				return true
			}
		})
		.map(([relativePath]) => relativePath)
	if (stale.length > 0) {
		console.error(`Generated scientific documentation is stale: ${stale.join(', ')}`)
		process.exitCode = 1
	} else {
		console.log('Generated scientific documentation is current.')
	}
} else {
	console.log('Use --stdout to render documents or --check to verify committed documents.')
}
